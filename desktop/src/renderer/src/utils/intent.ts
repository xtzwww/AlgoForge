/**
 * 一句话是不是在**要代码**。
 *
 * 面板只有一个输入框（2026-09-27 合并「问 AI / 让 AI 写代码」两个动作），
 * 送出去之前要先判断该走对话（chat）还是代写（insert）。
 *
 * 命中规则刻意**偏保守**：宁可把一句"要代码的话"送进对话——四档/五档的
 * 对话本身就能带代码，只是没有"填入编辑器"按钮——也不要把一句"问思路的
 * 话"送进代写——四档的 insert 会真的把一段代码插进编辑器，学生没要就插，
 * 比少一个按钮严重得多。
 *
 * 所以只认**生成动词**（写 / 实现 / 生成 …），不认话题词：句子里有"排序"
 * 不代表在要代码（"这道题为什么用排序？"是提问），有"写"才是。
 */

const GENERATE_COMMANDS = [
  '帮我写',
  '给我写',
  '帮我实现',
  '给我实现',
  '帮我生成',
  '帮我做',
  '给我做',
  '帮我改',
  '写一个',
  '写一段',
  '写一行',
  '写个',
  '写代码',
  '写出',
  '实现',
  '生成',
  '创建',
  '构造',
  '声明',
  '定义',
  '做一个',
  '建一个',
  '补全'
]

export function looksLikeCodeRequest(text: string): boolean {
  const t = text.trim()
  if (t === '') return false
  return GENERATE_COMMANDS.some((cmd) => t.includes(cmd))
}
