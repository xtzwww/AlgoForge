/**
 * 认证守卫（2026-10-04）。
 *
 * 把"这一页你能不能进"从**运行时分散判断**变成**路由表上的声明式字段**。
 * 改造前同一件事有八个副本：六个教师面板各写一遍
 * `if (!isTeacher.value) return`，`TeacherGate.vue` 再判一遍，
 * `AppTopbar.vue` 是第四遍。没有任何两处能保证一致，而且漏抄不报错。
 *
 * 三条铁律
 * --------
 * 下面每一条都对应一个**曾经真实发生过或极易发生**的 bug，不是风格偏好。
 */
import type { Router } from 'vue-router'
import { isLoggedIn, isTeacher, sessionReady } from '../../api/session'
import { landingName } from '../landing'
import { needsAuth, needsTeacher } from '../meta'
import { appMode } from '../../runtime/mode'

export function installAuthGuard(router: Router): void {
  router.beforeEach((to) => {
    // ------------------------------------------------------------------
    // 铁律 1：会话状态未知时一律放行，不做任何判断。
    //
    // `sessionReady` 为 false 表示"启动时那次 /auth/me 的往返还没回来"，
    // 此时 `isLoggedIn` 对**所有人**都是 false——包括一个有效会话正在
    // 被恢复的教师。在未知状态上做"未登录 → 去登录页"的判断，表现是
    // **每次刷新都被弹去登录页**，而刷新恰好是恢复会话的正常路径，于是
    // 用户永远登录不上。这个 bug 看起来像"登录坏了"，与它的原因（一个
    // 判断做早了）完全不像。
    //
    // 代价是"未登录的人可能看到一帧受保护页面"——但受保护页面自己会
    // 因为拿不到数据而显示加载态，比弹走一个已登录的人轻得多。
    // ------------------------------------------------------------------
    if (!sessionReady.value) return true

    // ------------------------------------------------------------------
    // 铁律 2：认证页永不参与判定，永远可达。
    //
    // 三件事都靠这一行：登录页不会要求登录（否则它重定向到自己，浏览器
    // 报"重定向次数过多"）、登录页不会做角色判定（一个已登录的人能打开
    // 它——`LoginView` 自己负责把他送走）、注册页同理。
    // ------------------------------------------------------------------
    if (to.meta.guestOnly) return true

    // ------------------------------------------------------------------
    // 铁律 3：只拦**声明过**的页。没写 `requiresAuth` / `requiresTeacher`
    // 就是公开页（练习、题库、题目详情都是），不做任何隐式拦截。
    // ------------------------------------------------------------------
    if (!needsAuth(to.meta)) return true

    // 已登录：教师页再判一次角色。
    if (isLoggedIn.value) {
      // 角色不符 → 回**自己的首页**，不是登录页。
      //
      // 这是本文件里最容易写错的一处。把人送去登录页看起来"更安全"，
      // 但他本来就是登录状态：他会以为"我没登录 / 登录坏了"，然后一遍
      // 遍重登，而那不会有任何帮助。回首页是一句诚实的话——这里你去
      // 不了——并且立刻给出一个他能用的地方。
      if (needsTeacher(to.meta) && !isTeacher.value) {
        return { name: landingName(appMode, 'student') }
      }
      return true
    }

    // 未登录 → 登录页。**不记原目标**（2026-10-04 的决定）：登录成功后
    // 固定去首页。若将来要支持"登录后回到刚才那一页"，在 `to.fullPath`
    // 上带一个 `?redirect=`，由 `LoginView` 成功后消费——注意那会引入
    // "开放重定向"风险，只接受站内路径。
    return { name: 'login' }
  })
}
